--count of restaurants per city
select count(restaurant_id),city from zomato_restaurants group by city

--Top 5 cities with highest number of orders

with grouping_orders AS (
select count(order_id) as count_of_orders, city from zomato_orders o JOIN zomato_restaurants t 
ON o.restaurant_id = t.restaurant_id group by city),
ranking AS (
select city,count_of_orders, DENSE_RANK() OVER(order by count_of_orders DESC) rk from grouping_orders
) 
select r.city,r.count_of_orders, r.rk from ranking r where r.rk <= 5;

--Calculate the total revenue generated by each restaurant.
select o.restaurant_id,r.restaurant_name, sum(o.total_cost) from zomato_orders o JOIN zomato_restaurants r
ON r.restaurant_id = o.restaurant_id 
group by o.restaurant_id,r.restaurant_name


--Find the average order amount for each city

select r.city, avg(o.total_cost) from zomato_orders o JOIN zomato_restaurants r
ON r.restaurant_id = o.restaurant_id 
group by r.city

--Identify the top 5 restaurants with the highest total sales.

with grouping_sales AS (
select sum(o.total_cost) as total_sales, o.restaurant_id,t.restaurant_name from zomato_orders o JOIN zomato_restaurants t 
ON o.restaurant_id = t.restaurant_id group by  o.restaurant_id,t.restaurant_name),
ranking AS (
select restaurant_name,total_sales, DENSE_RANK() OVER(order by total_sales DESC) rk from grouping_sales
) 
select r.restaurant_name,r.total_sales, r.rk from ranking r where r.rk <= 5;











